create table shipment (
    id           bigint generated by default as identity primary key,
    shipment_no  varchar(255) not null,
    status       varchar(255) not null check (status in ('PENDING', 'PROCESSING', 'FAILED', 'COMPLETED')),
    total_units  integer      not null,
    done_units   integer      not null,
    zip_key      varchar(255),
    created_at   timestamp(6) not null,
    completed_at timestamp(6),
    constraint uk_shipment_shipment_no unique (shipment_no)
);

create table packaging (
    id           bigint generated by default as identity primary key,
    packaging_no varchar(255) not null,
    type         varchar(255) not null check (type in ('BOX', 'VIRTUAL')),
    status       varchar(255) not null check (status in ('PENDING', 'PROCESSING', 'FAILED', 'COMPLETED')),
    shipment_id  bigint,
    created_at   timestamp(6) not null,
    completed_at timestamp(6),
    constraint uk_packaging_packaging_no unique (packaging_no),
    constraint fk_packaging_shipment foreign key (shipment_id) references shipment (id)
);

create table product (
    id           bigint generated by default as identity primary key,
    serial       varchar(255) not null,
    packaging_id bigint,
    file_id      bigint,
    constraint uk_product_serial unique (serial),
    constraint fk_product_packaging foreign key (packaging_id) references packaging (id)
);

create table inspection_file (
    id                 bigint generated by default as identity primary key,
    product_id         bigint       not null,
    inspected_at       timestamp(6) not null,
    sensor_id          varchar(255),
    uploader_equipment varchar(255),
    file_path          varchar(500) not null,
    created_at         timestamp(6) not null,
    constraint uk_inspection_file_product_id_inspected_at unique (product_id, inspected_at),
    constraint fk_inspection_file_product foreign key (product_id) references product (id)
);

create table number_rule (
    rule varchar(255) not null primary key check (rule in ('PACKAGING_NO', 'SHIPMENT_NO'))
);

create table number_counter (
    rule        varchar(255) not null check (rule in ('PACKAGING_NO', 'SHIPMENT_NO')),
    issued_date date         not null,
    last_value  integer      not null,
    primary key (rule, issued_date)
);
